/**
 * Extracts readable ASCII/Latin text runs from simple/uncompressed PDF streams
 * while handling plain-text, Markdown, JSON, or CSV documents directly.
 */
function extractReadablePdfText(rawBuffer: ArrayBuffer, filename: string): {
  text: string;
  note?: string;
} {
  const ext = filename.split('.').pop()?.toLowerCase() || '';
  const decoder = new TextDecoder('utf-8', { fatal: false });
  const raw = decoder.decode(rawBuffer);

  if (ext !== 'pdf' && !raw.startsWith('%PDF-')) {
    return { text: raw.slice(0, 45000) };
  }

  // Extract parenthesized PDF text objects inside BT...ET blocks or Tj/TJ operators
  const extractedChunks: string[] = [];
  const parenRegex = /\(([^()\\]*(?:\\.[^()\\]*)*)\)\s*(?:Tj|'|")?/g;
  let match: RegExpExecArray | null;
  while ((match = parenRegex.exec(raw)) !== null) {
    const cleaned = match[1]
      .replace(/\\n/g, '\n')
      .replace(/\\r/g, '')
      .replace(/\\t/g, ' ')
      .replace(/\\\(/g, '(')
      .replace(/\\\)/g, ')')
      .replace(/\\\\/g, '\\');
    // Filter out pure binary noise
    const printableRatio =
      cleaned.replace(/[^\x20-\x7E\n]/g, '').length / Math.max(cleaned.length, 1);
    if (cleaned.trim().length > 1 && printableRatio > 0.8) {
      extractedChunks.push(cleaned);
    }
  }

  const joined = extractedChunks.join(' ').replace(/\s{2,}/g, ' ').trim();
  if (joined.length > 120) {
    return { text: joined.slice(0, 45000) };
  }

  // Fallback notice for compressed FlateDecode/encrypted binary PDFs
  return {
    text: `[Compressed or Scanned PDF Detected: ${filename}]\n\nThis PDF uses binary compressed streams (FlateDecode) or embedded scanned images that require server-side OCR.\n\nTip: Export or save the document as plain text (.txt) or Markdown (.md), or explore one of the pre-loaded research papers from the Sample Library above.`,
    note: 'Compressed PDF stream detected',
  };
}

/**
 * Attempts to parse standard numbered MCQs generated by Gemini into interactive quiz cards.
 */
function parseMcqsFromMarkdown(md: string): ParsedMcq[] {
  const questions: ParsedMcq[] = [];
  const blocks = md.split(/\n(?=\*{0,2}(?:Q?\d+[\.\)]|\*\*Question\s*\d+))/i);

  for (const block of blocks) {
    const lines = block.trim().split('\n').map((l) => l.trim()).filter(Boolean);
    if (lines.length < 3) continue;

    const qMatch = lines[0].match(/^(?:\*{0,2}(?:Q|Question\s*)?(\d+)[\.\):\*]*\s*)(.+)/i);
    if (!qMatch) continue;

    const questionText = qMatch[2].replace(/\*\*/g, '').trim();
    const options: Array<{ key: string; text: string }> = [];
    let correctKey: string | null = null;
    let explanation: string | undefined;

    for (let i = 1; i < lines.length; i++) {
      const line = lines[i];
      const optMatch = line.match(/^(?:[-*]\s*)?\*{0,2}([A-D])[\)\.\:]\*{0,2}\s+(.+)/i);
      if (optMatch) {
        options.push({
          key: optMatch[1].toUpperCase(),
          text: optMatch[2].replace(/\*\*/g, '').trim(),
        });
        continue;
      }

      const ansMatch = line.match(/(?:Answer|Correct(?:\s+Answer)?)\s*[:\-]\s*\*{0,2}([A-D])\b/i);
      if (ansMatch) {
        correctKey = ansMatch[1].toUpperCase();
        const rest = line.split(/[A-D]\b[\.\)\*:]*/i).slice(1).join('').trim();
        if (rest.length > 4) explanation = rest.replace(/^[-–—:]\s*/, '');
        continue;
      }

      const expMatch = line.match(/^(?:Explanation|Rationale)\s*[:\-]\s*(.+)/i);
      if (expMatch) {
        explanation = expMatch[1].replace(/\*\*/g, '').trim();
      }
    }

    if (options.length >= 2) {
      questions.push({
        id: parseInt(qMatch[1], 10) || questions.length + 1,
        question: questionText,
        options,
        correctKey,
        explanation,
      });
    }
  }

  return questions;
}

export const PDFViewer: React.FC<PDFViewerProps> = ({
  tab,
  onSaveAsNote,
  onUpdateTabPdfData,
}) => {
  const currentPdf = tab.pdfData || null;

  const [activeAction, setActiveAction] = useState<string | null>(null);
  const [aiOutput, setAiOutput] = useState<string | null>(null);
  const [isLoading, setIsLoading] = useState(false);
  const [copied, setCopied] = useState(false);
  const [saved, setSaved] = useState(false);
  const [zoomLevel, setZoomLevel] = useState(100);
  const [customQuestion, setCustomQuestion] = useState('');
  const [mobileViewMode, setMobileViewMode] = useState<'doc' | 'ai'>('doc');

  // Workbench features: Search, Outline TOC, Sample Switcher, Text Selection Popover, Quiz Mode
  const [docSearch, setDocSearch] = useState('');
  const [activeMatchIdx, setActiveMatchIdx] = useState(0);
  const [showOutline, setShowOutline] = useState(true);
  const [selectedExcerpt, setSelectedExcerpt] = useState<string>('');
  const [quizViewMode, setQuizViewMode] = useState<'interactive' | 'markdown'>('interactive');
  const [quizAnswers, setQuizAnswers] = useState<Record<number, string>>({});
  const [quizSubmitted, setQuizSubmitted] = useState(false);

  const paperScrollRef = useRef<HTMLDivElement | null>(null);

  const handleSelectSample = (sample: (typeof SAMPLE_PDFS)[0]) => {
    onUpdateTabPdfData({
      filename: sample.filename,
      text: sample.text,
      pageCount: sample.pageCount,
      currentPage: 1,
    });
    setAiOutput(null);
    setActiveAction(null);
    setDocSearch('');
    setSelectedExcerpt('');
    setQuizAnswers({});
    setQuizSubmitted(false);
  };

  const handleFileUpload = (e: React.ChangeEvent<HTMLInputElement>) => {
    const file = e.target.files?.[0];
    if (!file) return;

    const reader = new FileReader();
    reader.onload = (event) => {
      const buffer = event.target?.result as ArrayBuffer;
      if (!buffer) return;
      const { text } = extractReadablePdfText(buffer, file.name);
      onUpdateTabPdfData({
        filename: file.name,
        text,
        pageCount: Math.max(1, Math.round(text.length / 2200)),
        currentPage: 1,
      });
      setAiOutput(null);
      setActiveAction(null);
      setDocSearch('');
      setSelectedExcerpt('');
    };
    reader.readAsArrayBuffer(file);
  };

  const handleRunAiAction = async (
    action: 'summarize' | 'notes' | 'mcq' | 'interview' | 'explain_simple' | 'ask',
    overrideQuery?: string
  ) => {
    if (!currentPdf) return;
    setActiveAction(action);
    setIsLoading(true);
    setAiOutput(null);
    setQuizAnswers({});
    setQuizSubmitted(false);
    setMobileViewMode('ai');

    try {
      const res = await analyzePDFDocument(
        currentPdf.text,
        currentPdf.filename,
        action,
        action === 'ask' || action === 'explain_simple'
          ? overrideQuery ?? customQuestion
          : undefined
      );
      setAiOutput(res.result);
    } catch (err: any) {
      setAiOutput(`Error analyzing document: ${err.message || 'Server error'}`);
    } finally {
      setIsLoading(false);
    }
  };

  // Document Lines & Auto-Generated Section Outline (TOC)
  const docLines = useMemo(() => {
    if (!currentPdf?.text) return [];
    return currentPdf.text.split('\n');
  }, [currentPdf?.text]);

  const outlineSections = useMemo(() => {
    const sections: Array<{ lineIndex: number; title: string }> = [];
    docLines.forEach((rawLine, idx) => {
      const line = rawLine.trim();
      if (!line || line.length > 90) return;
      const isMarkdownHeader = /^#{1,3}\s+/.test(line);
      const isNumberedSection = /^\d+(?:\.\d+)?\.\s+[A-Z]/.test(line) || /^\d+\.\d+\s+[A-Z]/.test(line);
      const isAllCapsHeading =
        line.length >= 4 &&
        line.length <= 55 &&
        /^[A-Z0-9\s\-\.\(\):]+$/.test(line) &&
        /[A-Z]{3,}/.test(line);

      if (isMarkdownHeader || isNumberedSection || isAllCapsHeading) {
        sections.push({
          lineIndex: idx,
          title: line.replace(/^#{1,3}\s+/, ''),
        });
      }
    });
    return sections;
  }, [docLines]);

  const wordStats = useMemo(() => {
    if (!currentPdf?.text) return { words: 0, readMin: 1 };
    const words = currentPdf.text.trim().split(/\s+/).filter(Boolean).length;
    return {
      words,
      readMin: Math.max(1, Math.ceil(words / 220)),
    };
  }, [currentPdf?.text]);

  // Search Match Indexing across lines
  const searchMatches = useMemo(() => {
    const q = docSearch.trim().toLowerCase();
    if (!q || !docLines.length) return [];
    const matches: Array<{ lineIndex: number }> = [];
    docLines.forEach((line, idx) => {
      if (line.toLowerCase().includes(q)) {
        matches.push({ lineIndex: idx });
      }
    });
    return matches;
  }, [docLines, docSearch]);

  const jumpToLine = (lineIndex: number) => {
    const el = paperScrollRef.current?.querySelector(`[data-line-idx="${lineIndex}"]`);
    if (el) {
      el.scrollIntoView({ behavior: 'smooth', block: 'center' });
    }
  };

  const cycleSearchMatch = (dir: 1 | -1) => {
    if (!searchMatches.length) return;
    const nextIdx = (activeMatchIdx + dir + searchMatches.length) % searchMatches.length;
    setActiveMatchIdx(nextIdx);
    jumpToLine(searchMatches[nextIdx].lineIndex);
  };

  const parsedMcqs = useMemo(() => {
    if (activeAction !== 'mcq' || !aiOutput) return [];
    return parseMcqsFromMarkdown(aiOutput);
  }, [activeAction, aiOutput]);

  const handlePaperMouseUp = () => {
    const sel = window.getSelection()?.toString().trim() || '';
    if (sel.length >= 8 && sel.length <= 1200) {
      setSelectedExcerpt(sel);
    }
  };

  const handleCopyResult = () => {
    if (aiOutput) {
      navigator.clipboard.writeText(aiOutput);
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    }
  };

  const handleDownloadReport = () => {
    if (!aiOutput || !currentPdf) return;
    const blob = new Blob([aiOutput], { type: 'text/markdown;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `${currentPdf.filename.replace(/\.[^/.]+$/, '')}-${activeAction || 'analysis'}.md`;
    a.click();
    URL.revokeObjectURL(url);
  };

  const handleSaveToNotes = () => {
    if (aiOutput && currentPdf) {
      onSaveAsNote(`${currentPdf.filename} · ${(activeAction || 'Analysis').toUpperCase()}`, aiOutput);
      setSaved(true);
      setTimeout(() => setSaved(false), 2500);
    }
  };

  if (!currentPdf) {
    return (
      <div className="h-full flex flex-col items-center justify-center bg-slate-50 p-6 select-none overflow-y-auto">
        <div className="w-full max-w-2xl bg-white border border-slate-200 rounded-2xl shadow-xs p-8 space-y-6">
          <div className="flex flex-col sm:flex-row sm:items-center gap-4 pb-6 border-b border-slate-200">
            <div className="w-12 h-12 rounded-xl bg-slate-900 text-white flex items-center justify-center shrink-0">
              <FileText className="w-6 h-6" />
            </div>
            <div className="space-y-1">
              <h2 className="text-lg font-semibold text-slate-900 tracking-tight">
                AI Document &amp; Research Workbench
              </h2>
              <p className="text-xs text-slate-600 leading-relaxed">
                Upload PDF, Markdown, or text documents to navigate auto-extracted outlines, search inline, generate Cornell study notes, and run interactive quizzes.
              </p>
            </div>
          </div>

          <div className="flex flex-wrap items-center gap-3">
            <label className="flex items-center justify-center gap-2 px-4 py-2.5 rounded-lg bg-slate-900 hover:bg-slate-800 text-white font-medium cursor-pointer transition-colors text-xs">
              <Upload className="w-4 h-4" />
              <span>Upload Document (.pdf, .txt, .md)</span>
              <input
                type="file"
                accept=".pdf,.txt,.md,.csv,.json"
                onChange={handleFileUpload}
                className="hidden"
              />
            </label>
          </div>

          <div className="space-y-2.5 pt-2">
            <div className="text-xs font-medium text-slate-500">
              Sample Research Library
            </div>
            <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
              {SAMPLE_PDFS.map((sample) => (
                <button
                  key={sample.id}
                  onClick={() => handleSelectSample(sample)}
                  className="p-4 rounded-xl border border-slate-200 hover:border-slate-400 bg-slate-50/60 hover:bg-white text-left transition-all cursor-pointer space-y-1.5"
                >
                  <div className="text-xs text-slate-500 font-mono">
                    {sample.filename} · {sample.pageCount} pages
                  </div>
                  <div className="text-sm font-semibold text-slate-900 leading-snug">
                    {sample.title}
                  </div>
                  <p className="text-xs text-slate-600 line-clamp-2 leading-relaxed">
                    {sample.description}
                  </p>
                </button>
              ))}
            </div>
          </div>
        </div>
      </div>
    );
  }

  return (
    <div className="h-full flex flex-col md:flex-row bg-slate-50 text-slate-900 overflow-hidden select-text">
      {/* Mobile Toggle: Document vs AI Analysis (< md) */}
      <div className="md:hidden h-10 px-3 bg-white border-b border-slate-200 flex items-center justify-between text-xs shrink-0 z-20">
        <div className="flex items-center gap-1 bg-slate-100 p-0.5 rounded-lg border border-slate-200">
          <button
            onClick={() => setMobileViewMode('doc')}
            className={`px-3 py-1 rounded-md font-medium text-xs transition-colors cursor-pointer ${
              mobileViewMode === 'doc'
                ? 'bg-white text-slate-900 shadow-2xs'
                : 'text-slate-600 hover:text-slate-900'
            }`}
          >
            Document
          </button>
          <button
            onClick={() => setMobileViewMode('ai')}
            className={`px-3 py-1 rounded-md font-medium text-xs transition-colors cursor-pointer ${
              mobileViewMode === 'ai'
                ? 'bg-white text-slate-900 shadow-2xs'
                : 'text-slate-600 hover:text-slate-900'
            }`}
          >
            AI Workbench
          </button>
        </div>
        <span className="text-[11px] font-mono text-slate-500 truncate max-w-[130px]">
          {currentPdf.filename}
        </span>
      </div>

      {/* Left Area: Document Paper + Outline Sidebar */}
      <div
        className={`flex-1 flex-col border-r border-slate-200 bg-slate-100 overflow-hidden ${
          mobileViewMode === 'doc' ? 'flex' : 'hidden md:flex'
        }`}
      >
        {/* Document Top Toolbar */}
        <div className="px-4 py-2 bg-white border-b border-slate-200 flex flex-wrap items-center justify-between gap-2 text-xs text-slate-700 shrink-0">
          <div className="flex items-center gap-2.5 min-w-0">
            <button
              onClick={() => setShowOutline((v) => !v)}
              className={`p-1.5 rounded-lg border transition-colors cursor-pointer ${
                showOutline
                  ? 'bg-slate-900 text-white border-slate-900'
                  : 'bg-slate-50 text-slate-600 border-slate-200 hover:bg-slate-100'
              }`}
              title="Toggle Section Outline"
            >
              <ListTree className="w-3.5 h-3.5" />
            </button>
            <div className="min-w-0">
              <div className="font-semibold text-slate-900 truncate max-w-[220px]">
                {currentPdf.filename}
              </div>
              <div className="text-[11px] text-slate-500 font-mono tabular-nums">
                {currentPdf.pageCount} pages · {wordStats.words} words · {wordStats.readMin} min read
              </div>
            </div>
          </div>

          {/* Search in Document + Zoom + Switcher + Upload */}
          <div className="flex items-center gap-2 flex-wrap">
            <div className="flex items-center bg-slate-50 border border-slate-200 rounded-lg px-2 py-1 gap-1">
              <Search className="w-3.5 h-3.5 text-slate-400 shrink-0" />
              <input
                type="text"
                value={docSearch}
                onChange={(e) => {
                  setDocSearch(e.target.value);
                  setActiveMatchIdx(0);
                }}
                placeholder="Find in document..."
                className="w-28 sm:w-36 bg-transparent text-xs text-slate-800 placeholder-slate-400 focus:outline-none"
              />
              {docSearch.trim() && (
                <>
                  <span className="text-[10px] font-mono tabular-nums text-slate-500 px-1">
                    {searchMatches.length ? `${activeMatchIdx + 1}/${searchMatches.length}` : '0'}
                  </span>
                  <button
                    onClick={() => cycleSearchMatch(-1)}
                    className="p-0.5 hover:bg-slate-200 rounded text-slate-600 cursor-pointer"
                    title="Previous Match"
                  >
                    <ChevronLeft className="w-3 h-3" />
                  </button>
                  <button
                    onClick={() => cycleSearchMatch(1)}
                    className="p-0.5 hover:bg-slate-200 rounded text-slate-600 cursor-pointer"
                    title="Next Match"
                  >
                    <ChevronRight className="w-3 h-3" />
                  </button>
                </>
              )}
            </div>

            <div className="flex items-center gap-1 bg-slate-50 px-1.5 py-0.5 rounded-lg text-slate-700 border border-slate-200">
              <button
                onClick={() => setZoomLevel((z) => Math.max(75, z - 10))}
                className="p-0.5 hover:text-slate-900 cursor-pointer"
                title="Zoom Out"
              >
                <ZoomOut className="w-3.5 h-3.5" />
              </button>
              <span className="text-[11px] font-mono tabular-nums px-1">{zoomLevel}%</span>
              <button
                onClick={() => setZoomLevel((z) => Math.min(140, z + 10))}
                className="p-0.5 hover:text-slate-900 cursor-pointer"
                title="Zoom In"
              >
                <ZoomIn className="w-3.5 h-3.5" />
              </button>
            </div>

            <select
              aria-label="Switch sample paper"
              value={SAMPLE_PDFS.find((s) => s.filename === currentPdf.filename)?.id || ''}
              onChange={(e) => {
                const found = SAMPLE_PDFS.find((s) => s.id === e.target.value);
                if (found) handleSelectSample(found);
              }}
              className="bg-slate-50 border border-slate-200 rounded-lg px-2 py-1 text-xs text-slate-700 focus:outline-none focus:border-cyan-600 cursor-pointer"
            >
              <option value="" disabled>
                Library...
              </option>
              {SAMPLE_PDFS.map((s) => (
                <option key={s.id} value={s.id}>
                  {s.title.slice(0, 32)}
                </option>
              ))}
            </select>

            <label className="flex items-center gap-1 px-2.5 py-1 rounded-lg bg-slate-900 hover:bg-slate-800 text-white font-medium cursor-pointer transition-colors">
              <Upload className="w-3.5 h-3.5" />
              <span className="hidden sm:inline">Upload</span>
              <input
                type="file"
                accept=".pdf,.txt,.md,.csv,.json"
                onChange={handleFileUpload}
                className="hidden"
              />
            </label>
          </div>
        </div>

        {/* Highlighted Selection Excerpt Action Bar */}
        {selectedExcerpt && (
          <div className="px-4 py-2 bg-cyan-50 border-b border-cyan-200 flex flex-wrap items-center justify-between gap-2 text-xs shrink-0">
            <div className="flex items-center gap-2 min-w-0 flex-1">
              <span className="font-medium text-cyan-900 shrink-0">Selected Excerpt:</span>
              <span className="italic text-cyan-800 truncate">"{selectedExcerpt}"</span>
            </div>
            <div className="flex items-center gap-1.5 shrink-0">
              <button
                onClick={() => {
                  handleRunAiAction(
                    'ask',
                    `Explain this specific excerpt clearly in context: "${selectedExcerpt}"`
                  );
                }}
                className="px-2.5 py-1 rounded-md bg-slate-900 hover:bg-slate-800 text-white font-medium cursor-pointer"
              >
                Explain Selection
              </button>
              <button
                onClick={() => {
                  onSaveAsNote(
                    `Excerpt · ${currentPdf.filename}`,
                    `> "${selectedExcerpt}"\n\n*Source: ${currentPdf.filename}*`
                  );
                  setSelectedExcerpt('');
                }}
                className="px-2.5 py-1 rounded-md bg-white border border-cyan-300 text-cyan-900 hover:bg-cyan-100 font-medium cursor-pointer"
              >
                Save Excerpt
              </button>
              <button
                onClick={() => setSelectedExcerpt('')}
                className="p-1 text-cyan-700 hover:text-cyan-900 cursor-pointer"
              >
                <X className="w-3.5 h-3.5" />
              </button>
            </div>
          </div>
        )}

        {/* Document Body: Optional Left Outline + Paper Sheet */}
        <div className="flex-1 flex overflow-hidden">
          {showOutline && outlineSections.length > 0 && (
            <aside className="hidden lg:flex w-56 bg-white border-r border-slate-200 flex-col shrink-0 overflow-y-auto p-3 space-y-2">
              <div className="text-[11px] font-semibold text-slate-500 px-2 pb-1 border-b border-slate-100">
                Document Outline ({outlineSections.length})
              </div>
              <div className="space-y-0.5">
                {outlineSections.map((sec, idx) => (
                  <button
                    key={idx}
                    onClick={() => jumpToLine(sec.lineIndex)}
                    className="w-full text-left px-2 py-1.5 rounded-md text-xs text-slate-700 hover:bg-slate-100 hover:text-slate-900 truncate cursor-pointer transition-colors"
                    title={sec.title}
                  >
                    {sec.title}
                  </button>
                ))}
              </div>
            </aside>
          )}

          {/* Scrollable Paper Surface */}
          <div
            ref={paperScrollRef}
            onMouseUp={handlePaperMouseUp}
            className="flex-1 overflow-y-auto p-6 md:p-8 flex justify-center bg-slate-100"
          >
            <div
              style={{ transform: `scale(${zoomLevel / 100})`, transformOrigin: 'top center' }}
              className="w-full max-w-2xl bg-white text-slate-900 rounded-xl shadow-sm border border-slate-200 p-8 md:p-12 transition-transform duration-150 space-y-6 select-text h-fit min-h-[620px]"
            >
              <div className="pb-6 border-b border-slate-200 space-y-1.5">
                <div className="text-xs text-slate-500 font-mono">
                  {currentPdf.filename} · {currentPdf.pageCount} pages
                </div>
                <h2 className="text-2xl font-semibold tracking-tight text-slate-900">
                  {currentPdf.filename.replace(/_/g, ' ').replace(/\.[^/.]+$/, '')}
                </h2>
              </div>

              <div className="text-sm leading-relaxed text-slate-800 space-y-2">
                {docLines.map((line, lineIdx) => {
                  const q = docSearch.trim();
                  const isSection = outlineSections.some((s) => s.lineIndex === lineIdx);
                  const isActiveSearchLine =
                    searchMatches[activeMatchIdx]?.lineIndex === lineIdx;

                  const renderContent = () => {
                    if (!q) return line || '\u00A0';
                    const regex = new RegExp(`(${q.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')})`, 'gi');
                    const parts = line.split(regex);
                    return parts.map((part, pIdx) =>
                      part.toLowerCase() === q.toLowerCase() ? (
                        <mark
                          key={pIdx}
                          className={`px-0.5 rounded-xs ${
                            isActiveSearchLine
                              ? 'bg-amber-300 text-slate-950 font-semibold'
                              : 'bg-amber-100 text-slate-900'
                          }`}
                        >
                          {part}
                        </mark>
                      ) : (
                        <React.Fragment key={pIdx}>{part}</React.Fragment>
                      )
                    );
                  };

                  return (
                    <p
                      key={lineIdx}
                      data-line-idx={lineIdx}
                      className={
                        isSection
                          ? 'text-base font-semibold text-slate-900 pt-3'
                          : 'whitespace-pre-wrap'
                      }
                    >
                      {renderContent()}
                    </p>
                  );
                })}
              </div>
            </div>
          </div>
        </div>
      </div>

      {/* Right Panel: AI Intelligence Workbench */}
      <div
        className={`w-full md:w-[450px] h-full bg-white flex-col z-10 select-text border-l border-slate-200 overflow-hidden ${
          mobileViewMode === 'ai' ? 'flex flex-1 md:flex-initial' : 'hidden md:flex'
        }`}
      >
        <div className="px-4 py-3 border-b border-slate-200 bg-white flex items-center justify-between shrink-0">
          <div>
            <h3 className="text-sm font-semibold text-slate-900">AI Document Workbench</h3>
            <p className="text-xs text-slate-500">
              Synthesis, Cornell study notes &amp; interactive testing
            </p>
          </div>
        </div>

        {/* Action Controls Grid */}
        <div className="p-3 border-b border-slate-200 grid grid-cols-2 gap-2 text-xs bg-slate-50 shrink-0">
          <button
            onClick={() => handleRunAiAction('summarize')}
            className={`p-2.5 rounded-lg border text-left flex items-center gap-2.5 transition-colors cursor-pointer ${
              activeAction === 'summarize'
                ? 'bg-slate-900 border-slate-900 text-white'
                : 'bg-white hover:bg-slate-100 border-slate-200 text-slate-800'
            }`}
          >
            <BookOpen className="w-4 h-4 shrink-0 opacity-80" />
            <div>
              <div className="font-medium">Executive Summary</div>
              <div className={`text-[10px] ${activeAction === 'summarize' ? 'text-slate-300' : 'text-slate-500'}`}>
                Core findings &amp; results
              </div>
            </div>
          </button>

          <button
            onClick={() => handleRunAiAction('notes')}
            className={`p-2.5 rounded-lg border text-left flex items-center gap-2.5 transition-colors cursor-pointer ${
              activeAction === 'notes'
                ? 'bg-slate-900 border-slate-900 text-white'
                : 'bg-white hover:bg-slate-100 border-slate-200 text-slate-800'
            }`}
          >
            <GraduationCap className="w-4 h-4 shrink-0 opacity-80" />
            <div>
              <div className="font-medium">Cornell Study Notes</div>
              <div className={`text-[10px] ${activeAction === 'notes' ? 'text-slate-300' : 'text-slate-500'}`}>
                Structured revision sheet
              </div>
            </div>
          </button>

          <button
            onClick={() => handleRunAiAction('mcq')}
            className={`p-2.5 rounded-lg border text-left flex items-center gap-2.5 transition-colors cursor-pointer ${
              activeAction === 'mcq'
                ? 'bg-slate-900 border-slate-900 text-white'
                : 'bg-white hover:bg-slate-100 border-slate-200 text-slate-800'
            }`}
          >
            <Sparkles className="w-4 h-4 shrink-0 opacity-80" />
            <div>
              <div className="font-medium">Practice Quiz (5 MCQs)</div>
              <div className={`text-[10px] ${activeAction === 'mcq' ? 'text-slate-300' : 'text-slate-500'}`}>
                Interactive test runner
              </div>
            </div>
          </button>

          <button
            onClick={() => handleRunAiAction('interview')}
            className={`p-2.5 rounded-lg border text-left flex items-center gap-2.5 transition-colors cursor-pointer ${
              activeAction === 'interview'
                ? 'bg-slate-900 border-slate-900 text-white'
                : 'bg-white hover:bg-slate-100 border-slate-200 text-slate-800'
            }`}
          >
            <Briefcase className="w-4 h-4 shrink-0 opacity-80" />
            <div>
              <div className="font-medium">Technical Q&amp;A</div>
              <div className={`text-[10px] ${activeAction === 'interview' ? 'text-slate-300' : 'text-slate-500'}`}>
                Deep defense questions
              </div>
            </div>
          </button>

          <button
            onClick={() => handleRunAiAction('explain_simple')}
            className={`col-span-2 p-2 rounded-lg border text-left flex items-center justify-between transition-colors cursor-pointer ${
              activeAction === 'explain_simple'
                ? 'bg-slate-900 border-slate-900 text-white'
                : 'bg-white hover:bg-slate-100 border-slate-200 text-slate-800'
            }`}
          >
            <div className="flex items-center gap-2">
              <Lightbulb className="w-3.5 h-3.5 shrink-0 opacity-80" />
              <span className="font-medium">Explain Simply (Intuition &amp; Analogies)</span>
            </div>
            <ArrowRight className="w-3.5 h-3.5 opacity-60" />
          </button>
        </div>

        {/* Custom Document Question Input */}
        <div className="p-3 border-b border-slate-200 bg-white shrink-0">
          <form
            onSubmit={(e) => {
              e.preventDefault();
              if (customQuestion.trim()) handleRunAiAction('ask');
            }}
            className="flex items-center gap-1.5"
          >
            <input
              type="text"
              value={customQuestion}
              onChange={(e) => setCustomQuestion(e.target.value)}
              placeholder="Ask anything about this document..."
              className="flex-1 bg-slate-50 border border-slate-200 rounded-lg px-3 py-1.5 text-xs text-slate-900 placeholder-slate-400 focus:outline-none focus:border-cyan-600 focus:bg-white"
            />
            <button
              type="submit"
              disabled={!customQuestion.trim() || isLoading}
              className="p-2 rounded-lg bg-slate-900 hover:bg-slate-800 disabled:opacity-40 text-white transition-colors cursor-pointer"
              title="Ask Question"
            >
              <ArrowRight className="w-3.5 h-3.5" />
            </button>
          </form>
        </div>

        {/* AI Results / Interactive Quiz Area */}
        <div className="flex-1 overflow-y-auto p-4 space-y-4 bg-white">
          {isLoading && (
            <div className="py-12 text-center space-y-3">
              <div className="w-8 h-8 rounded-full border-2 border-slate-900 border-t-transparent animate-spin mx-auto" />
              <p className="text-xs text-slate-700 font-medium">
                Analyzing document structure and synthesizing response...
              </p>
            </div>
          )}

          {!isLoading && aiOutput && (
            <div className="space-y-4">
              <div className="flex flex-wrap items-center justify-between gap-2 pb-2.5 border-b border-slate-200 text-xs">
                <div className="flex items-center gap-2">
                  <span className="font-semibold text-slate-900 capitalize">
                    {activeAction?.replace('_', ' ') || 'Analysis'}
                  </span>
                  {parsedMcqs.length > 0 && (
                    <div className="flex items-center p-0.5 bg-slate-100 rounded-md border border-slate-200">
                      <button
                        onClick={() => setQuizViewMode('interactive')}
                        className={`px-2 py-0.5 text-[11px] font-medium rounded cursor-pointer ${
                          quizViewMode === 'interactive'
                            ? 'bg-white text-slate-900 shadow-2xs'
                            : 'text-slate-600'
                        }`}
                      >
                        Quiz ({parsedMcqs.length})
                      </button>
                      <button
                        onClick={() => setQuizViewMode('markdown')}
                        className={`px-2 py-0.5 text-[11px] font-medium rounded cursor-pointer ${
                          quizViewMode === 'markdown'
                            ? 'bg-white text-slate-900 shadow-2xs'
                            : 'text-slate-600'
                        }`}
                      >
                        Raw Text
                      </button>
                    </div>
                  )}
                </div>

                <div className="flex items-center gap-1">
                  <button
                    onClick={handleSaveToNotes}
                    className="px-2 py-1 rounded-md bg-slate-100 hover:bg-slate-200 text-slate-700 flex items-center gap-1 text-[11px] font-medium cursor-pointer"
                  >
                    {saved ? (
                      <span className="text-emerald-700 flex items-center gap-0.5">
                        <Check className="w-3 h-3" /> Saved
                      </span>
                    ) : (
                      <>
                        <BookmarkPlus className="w-3.5 h-3.5" />
                        <span>Save</span>
                      </>
                    )}
                  </button>
                  <button
                    onClick={handleCopyResult}
                    className="px-2 py-1 rounded-md bg-slate-100 hover:bg-slate-200 text-slate-700 flex items-center gap-1 text-[11px] font-medium cursor-pointer"
                  >
                    {copied ? (
                      <span className="text-emerald-700 flex items-center gap-0.5">
                        <Check className="w-3 h-3" /> Copied
                      </span>
                    ) : (
                      <>
                        <Copy className="w-3.5 h-3.5" />
                        <span>Copy</span>
                      </>
                    )}
                  </button>
                  <button
                    onClick={handleDownloadReport}
                    className="px-2 py-1 rounded-md bg-slate-100 hover:bg-slate-200 text-slate-700 flex items-center gap-1 text-[11px] font-medium cursor-pointer"
                    title="Download Markdown"
                  >
                    <Download className="w-3.5 h-3.5" />
                  </button>
                </div>
              </div>

              {/* Interactive Quiz Runner (when MCQs parsed cleanly) */}
              {parsedMcqs.length > 0 && quizViewMode === 'interactive' ? (
                <div className="space-y-4">
                  {parsedMcqs.map((q) => {
                    const userChoice = quizAnswers[q.id];
                    const isCorrect = quizSubmitted && q.correctKey && userChoice === q.correctKey;
                    return (
                      <div
                        key={q.id}
                        className="p-3.5 rounded-xl border border-slate-200 bg-slate-50/60 space-y-2.5"
                      >
                        <div className="text-xs font-semibold text-slate-900 leading-snug">
                          {q.id}. {q.question}
                        </div>
                        <div className="space-y-1.5">
                          {q.options.map((opt) => {
                            const selected = userChoice === opt.key;
                            const isAns = q.correctKey === opt.key;
                            let btnStyle =
                              'bg-white border-slate-200 text-slate-800 hover:border-slate-400';
                            if (!quizSubmitted && selected) {
                              btnStyle = 'bg-slate-900 border-slate-900 text-white';
                            } else if (quizSubmitted) {
                              if (isAns) {
                                btnStyle = 'bg-emerald-50 border-emerald-400 text-emerald-900 font-medium';
                              } else if (selected && !isAns) {
                                btnStyle = 'bg-rose-50 border-rose-300 text-rose-900';
                              }
                            }
                            return (
                              <button
                                key={opt.key}
                                type="button"
                                disabled={quizSubmitted}
                                onClick={() =>
                                  setQuizAnswers((prev) => ({ ...prev, [q.id]: opt.key }))
                                }
                                className={`w-full text-left px-3 py-2 rounded-lg border text-xs flex items-start gap-2 transition-colors cursor-pointer ${btnStyle}`}
                              >
                                <span className="font-mono font-semibold shrink-0">{opt.key}.</span>
                                <span>{opt.text}</span>
                              </button>
                            );
                          })}
                        </div>
                        {quizSubmitted && (q.correctKey || q.explanation) && (
                          <div
                            className={`text-[11px] pt-1 ${
                              isCorrect ? 'text-emerald-700' : 'text-slate-600'
                            }`}
                          >
                            {q.correctKey && (
                              <span className="font-semibold">Answer: {q.correctKey}. </span>
                            )}
                            {q.explanation}
                          </div>
                        )}
                      </div>
                    );
                  })}

                  <div className="flex items-center justify-between pt-2">
                    {quizSubmitted ? (
                      <>
                        <div className="text-xs font-semibold text-slate-900 flex items-center gap-1.5">
                          <CheckCircle2 className="w-4 h-4 text-emerald-600" />
                          <span>
                            Score:{' '}
                            {
                              parsedMcqs.filter(
                                (q) => q.correctKey && quizAnswers[q.id] === q.correctKey
                              ).length
                            }{' '}
                            / {parsedMcqs.length}
                          </span>
                        </div>
                        <button
                          onClick={() => {
                            setQuizAnswers({});
                            setQuizSubmitted(false);
                          }}
                          className="px-3 py-1.5 rounded-lg border border-slate-200 hover:bg-slate-50 text-xs font-medium flex items-center gap-1 cursor-pointer"
                        >
                          <RotateCcw className="w-3.5 h-3.5" />
                          <span>Retake</span>
                        </button>
                      </>
                    ) : (
                      <button
                        onClick={() => setQuizSubmitted(true)}
                        className="w-full py-2 rounded-lg bg-slate-900 hover:bg-slate-800 text-white text-xs font-medium cursor-pointer"
                      >
                        Check Answers
                      </button>
                    )}
                  </div>
                </div>
              ) : (
                <div className="markdown-body text-slate-800 text-xs leading-relaxed">
                  <Markdown>{aiOutput}</Markdown>
                </div>
              )}
            </div>
          )}

          {!isLoading && !aiOutput && (
            <div className="py-16 text-center space-y-2 text-slate-400 text-xs">
              <Sparkles className="w-7 h-7 text-slate-300 mx-auto" />
              <p className="font-medium text-slate-700">Ready to analyze document</p>
              <p className="max-w-xs mx-auto text-slate-500">
                Select an action above, highlight any excerpt on the paper, or ask a question below.
              </p>
            </div>
          )}
        </div>
      </div>
    </div>
  );
};
